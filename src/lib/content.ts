/**
 * Selects a random emotional letter for a given theme, optionally constrained by a tag.
 *
 * @param theme - High-level emotional theme to pull content from.
 * @param tag - Optional tag to further qualify the requested content (e.g. "night", "grounding").
 * @returns A single letter rendered as a newline-joined string.
 *
 * @throws If the theme does not exist in the repository.
 * @throws If a tag is provided that is not associated with the theme.
 * @throws If the theme has no letters configured.
 *
 * @example
 * // Get any letter for the "sad" theme
 * const letter = getRandomLetter("sad");
 *
 * @example
 * // Get a "sad" letter that is tagged as gentle/soothing
 * const gentleSadLetter = getRandomLetter("sad", "gentle");
 */
export function getRandomLetter(
  theme: EmotionalLetterTheme,
  tag?: string,
): string {
  const letters = EMOTIONAL_LETTERS[theme];
  if (!letters || letters.length === 0) {
    throw new Error(`No letters configured for theme "${theme}"`);
  }

  if (tag) {
    const tagsForTheme = EMOTIONAL_LETTER_TAGS[theme] ?? [];
    if (!tagsForTheme.includes(tag)) {
      throw new Error(`No content for theme "${theme}" with tag "${tag}"`);
    }
  }

  const idx = Math.floor(Math.random() * letters.length);
  const chosen = letters[idx];
  if (!chosen || chosen.length === 0) {
    throw new Error(`Selected letter for theme "${theme}" is empty`);
  }

  return chosen.join("\n");
}
